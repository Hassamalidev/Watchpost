/*
 * Check results as probes report them (PRODUCT.md §8 check_results, §9.1). Probes send one object
 * per check; the API stores it idempotently by `id`.
 */
import { z } from "zod";
import { CHECK_ERROR_CODES } from "../constants/check-errors.js";
import { checkRegionSchema } from "./region.js";
import { checkEvidenceSchema } from "./evidence.js";

const ms = z.number().min(0).max(600_000);

/* Timing waterfall from the probe (§9.1 step 5), in milliseconds. */
export const timingsSchema = z.object({
  dns: ms.optional(),
  connect: ms.optional(),
  tls: ms.optional(),
  ttfb: ms.optional(),
  download: ms.optional(),
  total: ms,
});

export const tlsInfoSchema = z.object({
  validFrom: z.iso.datetime({ offset: true }),
  validTo: z.iso.datetime({ offset: true }),
  issuer: z.string().max(512),
  subject: z.string().max(512),
  /* SHA-256 fingerprint, colon-separated hex. */
  fingerprint256: z.string().max(128),
  daysRemaining: z.number().int(),
  protocol: z.string().max(32).optional(),
});

export const checkResultSchema = z
  .object({
    /* UUIDv7 generated by the probe; the idempotency key. */
    id: z.uuid(),
    monitorId: z.uuid(),
    region: checkRegionSchema,
    checkedAt: z.iso.datetime({ offset: true }),
    ok: z.boolean(),
    errorCode: z.enum(CHECK_ERROR_CODES).optional(),
    /* Short human-readable detail, for example "HTTP 502 from 203.0.113.9". */
    message: z.string().max(500).optional(),
    httpStatus: z.number().int().min(100).max(599).optional(),
    latencyMs: ms,
    timings: timingsSchema.optional(),
    ip: z.union([z.ipv4(), z.ipv6()]).optional(),
    tls: tlsInfoSchema.optional(),
    /* DNS answers, ping statistics and other type-specific facts. */
    details: z.record(z.string(), z.unknown()).optional(),
    /* Set when the check ran for a verification or "Test now" task. */
    taskId: z.uuid().optional(),
    /* What the probe kept of a response it didn't like; failed results only (P2-T04). */
    evidence: checkEvidenceSchema.optional(),
  })
  .refine((r) => r.ok || r.errorCode !== undefined, {
    message: "failed results need an errorCode",
    path: ["errorCode"],
  });

export type CheckResult = z.infer<typeof checkResultSchema>;
